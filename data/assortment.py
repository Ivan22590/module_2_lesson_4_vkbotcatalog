def get_category(category_id: str) -> Category | None:
    """Возвращает товарный раздел по его идентификатору.

    :param category_id: идентификатор раздела, например ``insoles``;
    :return: карточка раздела или None, если раздел не найден.
    """
    for category in CATEGORIES:
        if category["id"] == category_id:
            return category
    return None


def get_button_label(category: Category) -> str:
    """Возвращает подпись кнопки раздела, не длиннее 40 символов.

    Ограничение ВКонтакте: подпись кнопки — максимум 40 символов.

    :param category: карточка раздела;
    :return: подпись для кнопки клавиатуры.
    """
    label = category.get("button_label") or category["name"]
    return label[:40]


def build_assortment_list() -> str:
    """Формирует список товарных разделов ассортимента.

    :return: текст со списком разделов для отправки сообщением.
    """
    lines = ["Ассортимент салонов «Авиценна»", ""]
    lines.extend(
        f"{index}. {category['name']} — {category['short_description']}"
        for index, category in enumerate(CATEGORIES, start=1)
    )
    lines.append("")
    lines.append("Выберите раздел, чтобы узнать подробнее.")
    return "\n".join(lines)


def build_category_card(category: Category) -> str:
    """Формирует подробную карточку товарного раздела.

    :param category: карточка раздела;
    :return: текст карточки для отправки сообщением.
    """
    return "\n".join(
        [
            f"Раздел: {category['name']}",
            "",
            category["short_description"],
            "",
            category["description"],
            "",
            "Купить изделия можно в салонах «Авиценна» — адреса в разделе "
            "«Салоны и адреса».",
        ]
    )
