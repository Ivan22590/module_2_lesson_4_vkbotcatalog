def get_service(service_id: str) -> Service | None:
    """Возвращает услугу по ее идентификатору.

    :param id: идентификатор услуги, например ``consultation``;
    :return: карточка услуги или None, если услуга не найдена.
    """
    for service in SERVICES:
        if service["id"] == service_id:
            return service
    return None


def get_button_label(service: Service) -> str:
    """Возвращает подпись кнопки услуги, не длиннее 40 символов.

    Ограничение ВКонтакте: подпись кнопки — максимум 40 символов.

    :param service: карточка услуги;
    :return: подпись для кнопки клавиатуры.
    """
    label = service.get("button_label") or service["name"]
    return label[:40]


def build_price_list() -> str:
    """Формирует прайс-лист из базы знаний услуг.

    :return: текст прайс-листа для отправки сообщением.
    """
    lines = ["Прайс-лист ортопедического салона", ""]
    lines.extend(f"{service['name']} — {service['price']} ₽" for service in SERVICES)
    return "\n".join(lines)


def build_catalog_list() -> str:
    """Формирует краткий список услуг для каталога.

    :return: текст каталога с нумерованным списком услуг.
    """
    lines = ["Каталог услуг", ""]
    lines.extend(f"{index}. {service['name']}" for index, service in enumerate(SERVICES, start=1))
    lines.append("")
    lines.append("Выберите услугу, чтобы узнать подробности.")
    return "\n".join(lines)


def build_service_card(service: Service) -> str:
    """Формирует подробную карточку услуги.

    Поля длительность и показания выводятся только если они заданы.

    :param service: карточка услуги;
    :return: текст карточки для отправки сообщением.
    """
    parts: list[str] = [
        f"Услуга: {service['name']}",
        "",
        "Краткое описание:",
        service["short_description"],
        "",
        "Подробное описание:",
        service["description"],
        "",
        f"Цена: {service['price']} ₽",
    ]

    if duration := service.get("duration"):
        parts.append(f"Длительность: {duration}")
    if indications := service.get("indications"):
        parts.extend(["", f"Показания: {indications}"])

    parts.extend(["", "Для записи свяжитесь с менеджером."])
    return "\n".join(parts)


